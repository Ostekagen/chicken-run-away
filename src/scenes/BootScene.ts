import Phaser from 'phaser';
import { GAME_HEIGHT, GAME_WIDTH, TILESET_COLUMNS, TILE_SIZE } from '../config';
import { LEVELS } from '../levels';

// Frame sizes match docs/CONTRACTS.md. A spritesheet keeps the plain key, so a sprite made
// with just that key shows frame 0.
const SPRITESHEETS: [key: string, width: number, height: number][] = [
  ['chicken', 28, 28],
  ['butcher', 40, 56],
  ['worker', 28, 40],
  ['rat', 28, 16],
  ['dog', 40, 24],
  ['fox', 40, 24],
  ['goose', 28, 32],
  ['van', 96, 48],
  ['checkpoint', 24, 48],
];

const IMAGES = [
  'cleaver', 'egg', 'corn', 'golden-egg', 'goal',
  'powerup-egg-throw', 'powerup-flappy-wings', 'powerup-feather-armor', 'powerup-corn-rush', 'powerup-mighty-crow',
];

const THEMES = ['slaughterhouse', 'farm', 'road'];

const SOUNDS = [
  'sfx-jump', 'sfx-hit', 'sfx-stomp', 'sfx-corn', 'sfx-egg', 'sfx-powerup', 'sfx-checkpoint', 'sfx-crow',
  'music-slaughterhouse', 'music-farm', 'music-road', 'music-boss',
];

const ANIMATIONS: { key: string; texture: string; start: number; end: number; frameRate: number; loop: boolean }[] = [
  { key: 'chicken-idle', texture: 'chicken', start: 0, end: 0, frameRate: 1, loop: false },
  { key: 'chicken-run', texture: 'chicken', start: 1, end: 4, frameRate: 12, loop: true },
  { key: 'chicken-jump', texture: 'chicken', start: 5, end: 5, frameRate: 1, loop: false },
  { key: 'chicken-fall', texture: 'chicken', start: 6, end: 6, frameRate: 1, loop: false },
  { key: 'butcher-run', texture: 'butcher', start: 0, end: 3, frameRate: 10, loop: true },
  { key: 'butcher-throw', texture: 'butcher', start: 4, end: 4, frameRate: 1, loop: false },
  { key: 'worker-walk', texture: 'worker', start: 0, end: 1, frameRate: 5, loop: true },
  { key: 'rat-walk', texture: 'rat', start: 0, end: 1, frameRate: 8, loop: true },
  { key: 'dog-walk', texture: 'dog', start: 0, end: 1, frameRate: 8, loop: true },
  { key: 'fox-walk', texture: 'fox', start: 0, end: 1, frameRate: 8, loop: true },
  { key: 'goose-walk', texture: 'goose', start: 0, end: 1, frameRate: 6, loop: true },
  { key: 'van-drive', texture: 'van', start: 0, end: 1, frameRate: 12, loop: true },
];

// Loads levels, art and sound. The art is generated by tools/art/.
export class BootScene extends Phaser.Scene {
  constructor() {
    super('boot');
  }

  preload() {
    const barWidth = GAME_WIDTH / 2;
    const bar = this.add.rectangle((GAME_WIDTH - barWidth) / 2, GAME_HEIGHT / 2, 1, 12, 0xffe14d).setOrigin(0, 0.5);
    this.load.on('progress', (progress: number) => { bar.width = Math.max(1, barWidth * progress); });

    for (const level of LEVELS) this.load.tilemapTiledJSON(level, `levels/${level}.json`);
    for (const [key, frameWidth, frameHeight] of SPRITESHEETS) {
      this.load.spritesheet(key, `assets/sprites/${key}.png`, { frameWidth, frameHeight });
    }
    for (const key of IMAGES) this.load.image(key, `assets/sprites/${key}.png`);
    for (const theme of THEMES) {
      this.load.image(`tiles-${theme}`, `assets/tiles/tiles-${theme}.png`);
      this.load.image(`bg-${theme}`, `assets/backdrops/bg-${theme}.png`);
    }
    for (const key of SOUNDS) this.load.audio(key, `assets/audio/${key}.wav`);
  }

  create() {
    this.drawTiles();
    this.drawPigPen();
    for (const { key, texture, start, end, frameRate, loop } of ANIMATIONS) {
      this.anims.create({
        key,
        frames: this.anims.generateFrameNumbers(texture, { start, end }),
        frameRate,
        repeat: loop ? -1 : 0,
      });
    }
    this.scene.start('menu');
  }

  private drawPigPen() {
    const g = this.add.graphics();
    g.fillStyle(0x6b4a2f).fillRect(0, 26, 120, 14); // mud
    g.fillStyle(0x7c5836).fillEllipse(30, 28, 44, 8).fillEllipse(88, 30, 36, 6);
    g.fillStyle(0xc99a5b).fillRect(0, 8, 120, 4).fillRect(0, 18, 120, 4); // rails
    g.fillStyle(0xa87b45);
    for (let x = 0; x <= 112; x += 28) g.fillRect(x, 2, 8, 30); // posts
    g.generateTexture('pig-pen', 120, 40);
    g.destroy();
  }

  private drawTiles() {
    const g = this.add.graphics();
    // Tile 1: grass-topped ground.
    g.fillStyle(0x8a5a33).fillRect(0, 0, TILE_SIZE, TILE_SIZE);
    g.fillStyle(0x5fb548).fillRect(0, 0, TILE_SIZE, 8);
    // Tile 2: plain ground.
    g.fillStyle(0x8a5a33).fillRect(TILE_SIZE, 0, TILE_SIZE, TILE_SIZE);
    // Tile 3: one-way platform.
    g.fillStyle(0xc99a5b).fillRect(TILE_SIZE * 2, 0, TILE_SIZE, 10);
    // Tile 4: hazard.
    g.fillStyle(0xb8bcc4).fillTriangle(TILE_SIZE * 3, TILE_SIZE, TILE_SIZE * 3.5, 8, TILE_SIZE * 4, TILE_SIZE);
    g.generateTexture('tiles', TILE_SIZE * TILESET_COLUMNS, TILE_SIZE);
    g.destroy();
  }
}
